class ADCDataset(Dataset):
    """
    Multi-task dataset for ADC student training.

    self.samples is a flat list where each entry is a dict:
      {task, image_path, cls_label, label_path (yield only)}

    Teacher soft labels are loaded into memory at init:
      self.leaf_soft, self.pest_soft, self.fruit_soft : {stem → np.array}
      self.yield_soft                                  : {stem → list[dict]}
    """

    def __init__(
        self,
        cfg   : ADCConfig,
        split : str = "train",   # "train" or "val" or "test"
    ):
        super().__init__()
        self.cfg      = cfg
        self.split    = split
        self.mc       = cfg.model
        self.dc       = cfg.data
        pc            = cfg.paths
        is_train      = (split == "train")

        # ── Load teacher soft labels ─────────────────────────────────────────
        self.leaf_soft  = load_cls_soft_labels(pc.leaf_soft_csv,
                                               self.mc.num_leaf_classes)
        self.pest_soft  = load_cls_soft_labels(pc.pest_soft_csv,
                                               self.mc.num_pest_classes)
        self.fruit_soft = load_cls_soft_labels(pc.fruit_soft_csv,
                                               self.mc.num_fruit_classes)
        self.yield_soft = load_yield_soft_labels(pc.yield_soft_csv)

        # ── Collect samples from all tasks ───────────────────────────────────
        self.samples: List[Dict] = []

        # Classification tasks
        for task_name, data_root, class_map in [
            ("leaf",  pc.leaf_data_root,  LEAF_CLASS_MAP),
            ("pest",  pc.pest_data_root,  PEST_CLASS_MAP),
            ("fruit", pc.fruit_data_root, FRUIT_CLASS_MAP),
        ]:
            raw = _discover_cls_images(data_root, class_map, task_name)
            for img_path, cls_idx, task in raw:
                # For fruit task, look for a matching .txt annotation file
                lbl_path = None
                if task_name == "fruit":
                    txt = Path(img_path).with_suffix(".txt")
                    if txt.exists():
                        lbl_path = str(txt)

                self.samples.append({
                    "task"      : task_name,
                    "image_path": img_path,
                    "cls_label" : cls_idx,
                    "lbl_path"  : lbl_path,
                })

        # Yield task
        if split == "train":
            yield_imgs = _discover_yield_images(pc.yield_img_dir,
                                                pc.yield_label_dir)
        else:
            # For val/test: use yield val split
            val_img = str(Path(pc.yield_img_dir).parent.parent /
                          "images" / "val")
            val_lbl = str(Path(pc.yield_label_dir).parent.parent /
                          "labels" / "val")
            yield_imgs = _discover_yield_images(val_img, val_lbl)

        for img_path, lbl_path, task in yield_imgs:
            self.samples.append({
                "task"      : task,
                "image_path": img_path,
                "cls_label" : IGNORE,
                "lbl_path"  : lbl_path,
            })

        # ── Stratified split for classification images ────────────────────────
        # (Yield already has its own train/val split from the source dataset)
        if split != "train":
            self.samples = self._filter_to_val_test(split)

        # ── Transforms ───────────────────────────────────────────────────────
        if is_train:
            self.transforms = build_train_transforms(self.dc.image_size)
        self.val_transform = build_val_transform(self.dc.image_size)
        self.is_train = is_train

        print(f"[ADCDataset] split={split}  total={len(self.samples)}  "
              f"(leaf:{self._count('leaf')} pest:{self._count('pest')} "
              f"fruit:{self._count('fruit')} yield:{self._count('yield')})")

    # ─────────────────────────────────────────────────────────────────────────
    def _count(self, task: str) -> int:
        return sum(1 for s in self.samples if s["task"] == task)

    def _filter_to_val_test(self, split: str) -> List[Dict]:
        """
        Simple deterministic val/test split for classification samples.
        Yield samples are kept as-is (pre-split by source).
        """
        rng       = random.Random(self.dc.seed)
        by_task   = defaultdict(list)
        yield_samples = []

        for s in self.samples:
            if s["task"] == "yield":
                yield_samples.append(s)
            else:
                by_task[s["task"]].append(s)

        result = list(yield_samples)   # yield always included

        for task, slist in by_task.items():
            rng.shuffle(slist)
            n       = len(slist)
            n_test  = max(1, int(n * self.dc.test_split))
            n_val   = max(1, int(n * self.dc.val_split))
            n_train = n - n_test - n_val

            if split == "val":
                result.extend(slist[n_train : n_train + n_val])
            elif split == "test":
                result.extend(slist[n_train + n_val :])
            # "train" branch handled in __init__ before calling this

        return result

    # ─────────────────────────────────────────────────────────────────────────
    def __len__(self) -> int:
        return len(self.samples)

    # ─────────────────────────────────────────────────────────────────────────
    def __getitem__(self, idx: int) -> Dict:
        s    = self.samples[idx]
        task = s["task"]

        # ── Load image ───────────────────────────────────────────────────────
        try:
            img_np = np.array(Image.open(s["image_path"]).convert("RGB"))
        except (UnidentifiedImageError, OSError):
            img_np = np.zeros((self.dc.image_size, self.dc.image_size, 3),
                              dtype=np.uint8)

        # ── Load ground-truth boxes (yield and fruit with labels) ────────────
        gt_boxes = np.zeros((0, 4), dtype=np.float32)
        if task == "yield" and s["lbl_path"] is not None:
            gt_boxes = _load_yolo_boxes(s["lbl_path"])
        elif task == "fruit" and s["lbl_path"] is not None:
            gt_boxes = _load_yolo_boxes(s["lbl_path"])

        # ── Augmentation ─────────────────────────────────────────────────────
        if self.is_train:
            t = self.transforms[task]
            if task == "yield":
                aug = t(
                    image      = img_np,
                    bboxes     = gt_boxes.tolist() if len(gt_boxes) else [],
                    box_labels = [0] * len(gt_boxes),
                )
                img_t    = aug["image"]                            # [3, H, W]
                bboxes_a = np.array(aug["bboxes"], dtype=np.float32) \
                           if aug["bboxes"] else np.zeros((0, 4), dtype=np.float32)
            else:
                aug      = t(image=img_np)
                img_t    = aug["image"]
                bboxes_a = gt_boxes
        else:
            aug      = self.val_transform(image=img_np)
            img_t    = aug["image"]
            bboxes_a = gt_boxes

        # ── Classification labels ─────────────────────────────────────────────
        leaf_label  = s["cls_label"] if task == "leaf"  else IGNORE
        pest_label  = s["cls_label"] if task == "pest"  else IGNORE
        fruit_label = s["cls_label"] if task == "fruit" else IGNORE

        # ── Teacher soft labels (Multi-key fallback lookup) ───────────────────
        img_path_str = s["image_path"]
        keys_to_try  = _path_keys(img_path_str)

        # Helper to search all key variations before falling back to uniform prior
        def _get_soft_cls(table_dict, default_num_cls):
            for k in keys_to_try:
                if k in table_dict:
                    return table_dict[k]
            return np.full(default_num_cls, 1.0 / default_num_cls, dtype=np.float32)

        leaf_soft  = torch.from_numpy(_get_soft_cls(self.leaf_soft, self.mc.num_leaf_classes))
        pest_soft  = torch.from_numpy(_get_soft_cls(self.pest_soft, self.mc.num_pest_classes))
        fruit_soft = torch.from_numpy(_get_soft_cls(self.fruit_soft, self.mc.num_fruit_classes))

        # ── Yield teacher boxes lookup ────────────────────────────────────────
        t_yield_raw = []
        for k in keys_to_try:
            if k in self.yield_soft:
                t_yield_raw = self.yield_soft[k]
                break

        if t_yield_raw:
            t_yield_np = np.array(
                [xyxy_to_cxcywh(b["xyxy"]) + [b["conf"]] for b in t_yield_raw],
                dtype=np.float32,
            )   # [K, 5]
        else:
            t_yield_np = np.zeros((0, 5), dtype=np.float32)

        return {
            # ── Core ──────────────────────────────────────────────────────────
            "image"       : img_t,                         # [3, H, W]
            "task"        : task,
            "image_path"  : s["image_path"],

            # ── Ground-truth classification labels ────────────────────────────
            "leaf_label"  : torch.tensor(leaf_label,  dtype=torch.long),
            "pest_label"  : torch.tensor(pest_label,  dtype=torch.long),
            "fruit_label" : torch.tensor(fruit_label, dtype=torch.long),

            # ── Teacher soft labels (probs, T=1, used in distillation loss) ───
            "leaf_soft"   : leaf_soft,     # [num_leaf_classes]
            "pest_soft"   : pest_soft,     # [num_pest_classes]
            "fruit_soft"  : fruit_soft,    # [num_fruit_classes]

            # ── Ground-truth detection boxes (yield/fruit task) ───────────────
            "gt_boxes"    : torch.from_numpy(bboxes_a),   # [N, 4] (cx, cy, w, h)

            # ── Teacher detection boxes (cx, cy, w, h, conf normalised) ───────
            "teacher_boxes": torch.from_numpy(t_yield_np),  # [K, 5]
        }


# ===========================================================================
#  COLLATE FUNCTION  (handles variable-length box lists)
# ===========================================================================

def adc_collate_fn(batch: List[Dict]) -> Dict:
    """
    Custom collate that stacks tensors where possible and pads box lists.

    gt_boxes      : padded to [B, max_gt, 4],   validity mask in gt_mask
    teacher_boxes : padded to [B, max_tk, 5],   validity mask in teacher_mask
    """
    images       = torch.stack([s["image"]       for s in batch])
    leaf_labels  = torch.stack([s["leaf_label"]  for s in batch])
    pest_labels  = torch.stack([s["pest_label"]  for s in batch])
    fruit_labels = torch.stack([s["fruit_label"] for s in batch])
    leaf_soft    = torch.stack([s["leaf_soft"]   for s in batch])
    pest_soft    = torch.stack([s["pest_soft"]   for s in batch])
    fruit_soft   = torch.stack([s["fruit_soft"]  for s in batch])

    tasks        = [s["task"]       for s in batch]
    paths        = [s["image_path"] for s in batch]

    # ── Pad gt_boxes ─────────────────────────────────────────────────────────
    gt_lens  = [s["gt_boxes"].shape[0] for s in batch]
    max_gt   = max(gt_lens) if max(gt_lens) > 0 else 1
    B        = len(batch)

    gt_boxes_padded  = torch.zeros(B, max_gt, 4)
    gt_mask          = torch.zeros(B, max_gt, dtype=torch.bool)
    gt_img_idx       = []   # flat list: which image each box belongs to

    for i, s in enumerate(batch):
        n = s["gt_boxes"].shape[0]
        if n > 0:
            gt_boxes_padded[i, :n] = s["gt_boxes"]
            gt_mask[i, :n]         = True
            gt_img_idx.extend([i] * n)

    # ── Pad teacher_boxes ─────────────────────────────────────────────────────
    tk_lens  = [s["teacher_boxes"].shape[0] for s in batch]
    max_tk   = max(tk_lens) if max(tk_lens) > 0 else 1

    tk_boxes_padded = torch.zeros(B, max_tk, 5)
    tk_mask         = torch.zeros(B, max_tk, dtype=torch.bool)

    for i, s in enumerate(batch):
        n = s["teacher_boxes"].shape[0]
        if n > 0:
            tk_boxes_padded[i, :n] = s["teacher_boxes"]
            tk_mask[i, :n]         = True

    # ── Flat gt box list for ROI Align input ──────────────────────────────────
    # roi_boxes [M, 4] + roi_img_idx [M] (where M = total valid gt boxes in batch)
    flat_boxes   = gt_boxes_padded[gt_mask]       # [M, 4]
    flat_img_idx = torch.tensor(gt_img_idx, dtype=torch.long)

    return {
        "image"          : images,            # [B, 3, H, W]
        "task"           : tasks,             # list[str]
        "image_path"     : paths,

        "leaf_label"     : leaf_labels,       # [B]
        "pest_label"     : pest_labels,       # [B]
        "fruit_label"    : fruit_labels,      # [B]

        "leaf_soft"      : leaf_soft,         # [B, 5]
        "pest_soft"      : pest_soft,         # [B, 4]
        "fruit_soft"     : fruit_soft,        # [B, 3]

        # Ground-truth detection
        "gt_boxes"       : gt_boxes_padded,   # [B, max_gt, 4]
        "gt_mask"        : gt_mask,           # [B, max_gt]  bool

        # Flat boxes for ROI Align in model.forward()
        "roi_boxes"      : flat_boxes,        # [M, 4]  cx,cy,w,h normalised
        "roi_img_idx"    : flat_img_idx,      # [M]

        # Teacher detection
        "teacher_boxes"  : tk_boxes_padded,   # [B, max_tk, 5]
        "teacher_mask"   : tk_mask,           # [B, max_tk]  bool
    }


