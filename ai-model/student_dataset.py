"""
student_dataset.py
==================
Multi-task dataset for AgroDistill-Cascade (ADC) student training.

Each image belongs to ONE primary task (leaf / pest / fruit / yield).
Non-applicable tasks receive ignore_index=-1 (classification) or empty
tensors (detection), so the loss functions can mask them out correctly.

Teacher soft labels are loaded into memory at init from the four CSVs
generated by the teacher training pipeline.

Returns per-sample dict — see __getitem__ for full schema.
Custom collate_fn handles variable-length bounding box lists.
"""

