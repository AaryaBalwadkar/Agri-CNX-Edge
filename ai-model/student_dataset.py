def _discover_cls_images(
    data_root  : str,
    class_map  : Dict[str, int],
    task_name  : str,
) -> List[Tuple[str, int, str]]:
    """
    Returns [(image_path, class_idx, task_name)] for a classification task.
    Searches `data_root/{class_name}/` sub-folders.
    """
    samples = []
    root = Path(data_root)
    for cls_name, cls_idx in class_map.items():
        cls_dir = root / cls_name
        if not cls_dir.exists():
            print(f"[WARN] [{task_name}] Class folder missing: {cls_dir}")
            continue
        for f in cls_dir.rglob("*"):
            if f.suffix.lower() in SUPPORTED_EXTS:
                samples.append((str(f), cls_idx, task_name))
    return samples


def _discover_yield_images(
    img_dir  : str,
    lbl_dir  : str,
) -> List[Tuple[str, str, str]]:
    """
    Returns [(image_path, label_path, "yield")].
    label_path is the YOLO .txt annotation file (may not exist for negatives).
    """
    samples = []
    img_root = Path(img_dir)
    lbl_root = Path(lbl_dir)
    for img_path in sorted(img_root.iterdir()):
        if img_path.suffix.lower() not in SUPPORTED_EXTS:
            continue
        lbl_path = lbl_root / (img_path.stem + ".txt")
        samples.append((str(img_path), str(lbl_path), "yield"))
    return samples


def _load_yolo_boxes(txt_path: str) -> np.ndarray:
    """
    Loads YOLO-format ground-truth boxes from a .txt file.
    Returns [N, 4] float32 array of (cx, cy, w, h) in [0,1].
    Returns empty [0,4] if file absent or empty.
    """
    if not os.path.exists(txt_path):
        return np.zeros((0, 4), dtype=np.float32)
    boxes = []
    with open(txt_path) as f:
        for line in f:
            parts = line.strip().split()
            if len(parts) >= 5:
                # cls_id cx cy w h
                boxes.append([float(p) for p in parts[1:5]])
    return np.array(boxes, dtype=np.float32) if boxes else np.zeros((0, 4), dtype=np.float32)


# ===========================================================================
#  AUGMENTATION PIPELINES
# ===========================================================================

_IMAGENET_MEAN = [0.485, 0.456, 0.406]
_IMAGENET_STD  = [0.229, 0.224, 0.225]

_BBOX_PARAMS = A.BboxParams(
    format        = "yolo",       # cx,cy,w,h normalised
    label_fields  = ["box_labels"],
    min_visibility= 0.1,
)


def _norm(sz: int) -> List:
    return [A.Normalize(mean=_IMAGENET_MEAN, std=_IMAGENET_STD), ToTensorV2()]


def build_train_transforms(image_size: int) -> Dict[str, A.Compose]:
    """Per-task training augmentation. Yield uses BboxParams."""
    return {
        "leaf": A.Compose([
            A.RandomResizedCrop(size=(image_size, image_size),
                                scale=(0.65, 1.0), ratio=(0.75, 1.33)),
            A.HorizontalFlip(p=0.5),
            A.ColorJitter(brightness=0.3, contrast=0.3,
                          saturation=0.3, hue=0.1, p=0.5),
            A.GaussianBlur(blur_limit=(3, 7), p=0.2),
            A.GaussNoise(p=0.2),
            *_norm(image_size),
        ]),

        "pest": A.Compose([
            A.RandomResizedCrop(size=(image_size, image_size),
                                scale=(0.60, 1.0), ratio=(0.75, 1.33)),
            A.HorizontalFlip(p=0.5),
            A.VerticalFlip(p=0.2),
            A.Rotate(limit=20, p=0.4),
            A.CoarseDropout(num_holes_range=(1, 4),
                            hole_height_range=(16, 48),
                            hole_width_range=(16, 48),
                            fill=0, p=0.4),
            *_norm(image_size),
        ]),

        "fruit": A.Compose([
            A.RandomResizedCrop(size=(image_size, image_size),
                                scale=(0.65, 1.0)),
            A.HorizontalFlip(p=0.5),
            A.ColorJitter(brightness=0.3, contrast=0.3,
                          saturation=0.3, hue=0.1, p=0.5),
            *_norm(image_size),
        ]),

        # Yield: spatial augmentation is MINIMAL — heavy spatial transforms
        # break bbox validity. Color-only + hflip (with bbox mirroring).
        "yield": A.Compose([
            A.Resize(image_size, image_size),
            A.HorizontalFlip(p=0.5),
            A.ColorJitter(brightness=0.3, contrast=0.3,
                          saturation=0.3, hue=0.1, p=0.5),
            *_norm(image_size),
        ], bbox_params=_BBOX_PARAMS),
    }


def build_val_transform(image_size: int) -> A.Compose:
    """Shared val/test transform — resize + normalise only."""
    rs = int(image_size * 256 / 224)
    return A.Compose([
        A.Resize(rs, rs),
        A.CenterCrop(image_size, image_size),
        *_norm(image_size),
    ])


