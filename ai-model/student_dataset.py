def _stem(path: str) -> str:
    """Normalised key: filename stem without extension, lowercase."""
    return Path(path).stem.lower()


# ===========================================================================
#  TEACHER SOFT-LABEL LOADERS
# ===========================================================================

def _path_keys(path_str: str) -> List[str]:
    """
    Returns a list of key variations to guarantee soft-label match:
    1. Full normalized path string
    2. Filename stem (lowercase, e.g. 'lpu_rdp_m503')
    3. Filename with extension (e.g. 'lpu_rdp_m503.jpeg')
    4. Relative subpath (e.g. 'apple_mosaic/lpu_rdp_m503.jpeg')
    """
    p = Path(path_str)
    stem = p.stem.lower()
    name = p.name.lower()
    full = p.as_posix().lower()
    
    keys = [full, stem, name]
    if len(p.parts) >= 2:
        subpath = f"{p.parts[-2]}/{p.name}".lower()
        keys.append(subpath)
        
    return keys


def load_cls_soft_labels(csv_path: str, num_classes: int) -> Dict[str, np.ndarray]:
    """
    Reads a classification soft-label CSV.
    Handles both 'prob_X' and 'logit_X' columns, applies Softmax to logits,
    auto-pads if the CSV has fewer class columns than num_classes,
    and maps multiple key variations per image.
    """
    table: Dict[str, np.ndarray] = {}
    if not os.path.exists(csv_path):
        print(f"[WARN] Soft-label CSV not found: {csv_path}")
        return table

    with open(csv_path, newline="", encoding="utf-8") as f:
        reader = csv.reader(f)
        header = next(reader, None)
        if not header:
            return table

        # Normalize header strings
        clean_header = [col.strip().lower() for col in header]

        # Determine start column index for prob / logit values
        start_idx = -1
        is_logit = False

        for idx, col in enumerate(clean_header):
            if col.startswith("prob_") or col.startswith("logit_"):
                start_idx = idx
                if col.startswith("logit_"):
                    is_logit = True
                break

        # Fallback if specific header prefix isn't matched
        if start_idx == -1:
            if len(clean_header) >= 4 and "class_name" in clean_header:
                start_idx = 3
            else:
                start_idx = 1

        for row in reader:
            if not row or len(row) <= start_idx:
                continue

            raw_path = row[0].strip()
            
            try:
                # Read ALL available float values starting at start_idx
                vals = [float(x) for x in row[start_idx:] if x.strip() != ""]
            except (ValueError, IndexError):
                continue

            if not vals:
                continue

            probs = np.array(vals, dtype=np.float32)

            # Convert raw logits to probabilities via Softmax if CSV contains logits
            if is_logit:
                exp_vals = np.exp(probs - np.max(probs))  # Numerically stable softmax
                probs = exp_vals / np.sum(exp_vals)

            # Pad with zeros if CSV has fewer columns than num_classes (e.g., 4 columns vs 5 configured classes)
            if len(probs) < num_classes:
                padded = np.zeros(num_classes, dtype=np.float32)
                padded[:len(probs)] = probs
                probs = padded
            elif len(probs) > num_classes:
                probs = probs[:num_classes]

            # Map to all path key variations
            for k in _path_keys(raw_path):
                table[k] = probs

    print(f"[Dataset] Loaded {len(table)} soft label key entries from {Path(csv_path).name}")
    return table


def load_yield_soft_labels(csv_path: str) -> Dict[str, List[Dict]]:
    """
    Reads the yield soft-label CSV (json_boxes column).
    Returns {key → [{"xyxy":[x1,y1,x2,y2], "conf":float}, ...]}.
    """
    table: Dict[str, List[Dict]] = {}
    if not os.path.exists(csv_path):
        print(f"[WARN] Yield soft-label CSV not found: {csv_path}")
        return table

    with open(csv_path, newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            try:
                raw_path = row["image_path"].strip()
                boxes = json.loads(row["json_boxes"])
                for k in _path_keys(raw_path):
                    table[k] = boxes
            except (KeyError, json.JSONDecodeError):
                continue

    print(f"[Dataset] Loaded {len(table)} yield soft-label entries from "
          f"{Path(csv_path).name}")
    return table


def xyxy_to_cxcywh(xyxy: List[float]) -> List[float]:
    """Normalised XYXY → normalised CXCYWH."""
    x1, y1, x2, y2 = xyxy
    cx = (x1 + x2) / 2.0
    cy = (y1 + y2) / 2.0
    w  = x2 - x1
    h  = y2 - y1
    return [cx, cy, w, h]


