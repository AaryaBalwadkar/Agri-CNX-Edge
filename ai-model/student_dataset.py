def build_dataloaders(cfg: ADCConfig):
    """
    Returns (train_loader, val_loader).
    DataLoaders use adc_collate_fn for variable-length box handling.
    """
    train_ds = ADCDataset(cfg, split="train")
    val_ds   = ADCDataset(cfg, split="val")

    tc = cfg.train
    dc = cfg.data

    train_loader = DataLoader(
        train_ds,
        batch_size  = tc.batch_size,
        shuffle     = True,
        num_workers = dc.num_workers,
        pin_memory  = dc.pin_memory,
        collate_fn  = adc_collate_fn,
        drop_last   = True,
    )
    val_loader = DataLoader(
        val_ds,
        batch_size  = tc.batch_size * 2,
        shuffle     = False,
        num_workers = dc.num_workers,
        pin_memory  = dc.pin_memory,
        collate_fn  = adc_collate_fn,
    )

    return train_loader, val_loader